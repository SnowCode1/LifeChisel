// Reuse the already-bundled Tabler Outline paths, without importing its full
// catalogue into the offline DOM editor bundle.
import { writeFile } from 'node:fs/promises';
import { format } from 'prettier';
import assert from 'node:assert/strict';
import { tablerPaths } from '../packages/core/src/tablerPaths.ts';
const icons = {
  undo: 'arrow-back-up',
  redo: 'arrow-forward-up',
  bold: 'bold',
  italic: 'italic',
  text: 'typography',
  link: 'link',
  highlight: 'highlight',
  heading: 'h-2',
  bullets: 'list',
  numbered: 'list-numbers',
  quote: 'blockquote',
  strike: 'strikethrough',
  code: 'code',
  clear: 'clear-formatting',
};
const paths = Object.fromEntries(
  Object.entries(icons).map(([name, id]) => {
    assert.ok(tablerPaths[id]?.length, `Missing bundled Tabler icon ${id}`);
    return [name, tablerPaths[id]];
  }),
);
await writeFile(
  new URL('../src/editorIconPaths.ts', import.meta.url),
  await format(
    '// Generated by scripts/generate-editor-icons.mjs from the bundled Tabler Outline 3.48.0 paths.\n// MIT: docs/licenses/TABLER_LICENSE.txt.\nexport const editorIconPaths = ' +
      JSON.stringify(paths) +
      ' as const;\nexport type EditorIconName = keyof typeof editorIconPaths;\n',
    { parser: 'typescript', singleQuote: true, trailingComma: 'all' },
  ),
);
