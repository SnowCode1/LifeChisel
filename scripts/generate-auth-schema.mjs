// Writes the D1 migration for the sync server's sign-in tables from the same
// Better Auth settings the Worker uses (apps/sync/src/auth.ts), so the tables
// cannot drift from the code. Run after changing auth plugins or fields:
//   node scripts/generate-auth-schema.mjs
// It only creates migrations/0001_auth.sql; later changes need a new numbered
// migration, because applied migrations must never change.
import { DatabaseSync } from 'node:sqlite';
import { existsSync, writeFileSync } from 'node:fs';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../apps/sync/src/auth.ts';

const target = new URL(
  '../apps/sync/migrations/0001_auth.sql',
  import.meta.url,
);
if (existsSync(target) && !process.argv.includes('--force')) {
  console.error(
    'apps/sync/migrations/0001_auth.sql exists. Add a new numbered migration instead, or pass --force before it has been applied anywhere.',
  );
  process.exit(1);
}

const options = authOptions({
  database: new DatabaseSync(':memory:'),
  baseURL: 'http://localhost:8787',
  secret: 'schema-generation-only-secret-0000000000',
  appOrigins: [],
  passkeyRpId: 'localhost',
  passwordSignIn: true,
  signupAllowlist: null,
});
const { compileMigrations, unsafeChanges, schemaProblems } =
  await getMigrations(options);
if (unsafeChanges.length > 0 || schemaProblems.length > 0) {
  console.error([...unsafeChanges, ...schemaProblems].join('\n'));
  process.exit(1);
}
const sql = await compileMigrations();
writeFileSync(
  target,
  `-- Generated by scripts/generate-auth-schema.mjs (Better Auth sign-in tables).\n-- Never edit after it has been applied; add a new numbered migration.\n${sql.trim()}\n`,
);
console.log(`Wrote ${target.pathname}`);
